#!/usr/bin/env python3
"""Generate embedded Persian audio at build time from Piper, WAV files or fallback eSpeak."""
import argparse
import array
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

CLIPS = [
    ("DALI", "دالی!"),
    ("RED", "قرمز"),
    ("BLUE", "آبی"),
    ("YELLOW", "زرد"),
    ("BRAVO", "آفرین!"),
    ("TRY", "دوباره امتحان کن"),
    ("FIND_RED", "قرمز رو پیدا کن"),
    ("FIND_BLUE", "آبی رو پیدا کن"),
    ("FIND_YELLOW", "زرد رو پیدا کن"),
]

def ulaw_encode(sample):
    sign = 0x80 if sample < 0 else 0
    sample = min(32635, abs(sample) + 132)
    exponent = 7
    mask = 0x4000
    while exponent > 0 and not (sample & mask):
        exponent -= 1
        mask >>= 1
    mantissa = (sample >> (exponent + 3)) & 0x0F
    return (~(sign | (exponent << 4) | mantissa)) & 0xFF

def wav_to_ulaw(path, target_rate=16000):
    with wave.open(str(path), "rb") as f:
        if f.getsampwidth() != 2 or f.getnchannels() != 1:
            raise ValueError("Expected 16-bit mono WAV from espeak")
        rate = f.getframerate()
        pcm = array.array("h")
        pcm.frombytes(f.readframes(f.getnframes()))
        if sys.byteorder == "big":
            pcm.byteswap()
    count = max(1, round(len(pcm) * target_rate / rate))
    out = bytearray()
    for i in range(count):
        pos = i * rate / target_rate
        p = min(int(pos), len(pcm) - 1)
        q = min(p + 1, len(pcm) - 1)
        sample = round(pcm[p] + (pcm[q] - pcm[p]) * (pos - p))
        out.append(ulaw_encode(sample))
    return bytes(out)

def render_piper(model_path, wav, text):
    from piper import PiperVoice
    voice = render_piper._voice
    if voice is None:
        voice = PiperVoice.load(str(model_path))
        render_piper._voice = voice
    with wave.open(str(wav), "wb") as handle:
        voice.synthesize_wav(text, handle)

render_piper._voice = None

def generate(out, engine="espeak", model_path=None, recording_dir=None):
    lines = [
        "// Auto-generated by tools/generate_play_audio.py - DO NOT EDIT",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "namespace stackchan::app::play_audio {",
        "struct Clip { const std::uint8_t* data; std::size_t size; };",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for name, phrase in CLIPS:
            wav = Path(tmp) / (name.lower() + ".wav")
            recording = (recording_dir / (name.lower() + ".wav")) if recording_dir else None
            if recording is not None and recording.is_file():
                wav = recording
                print(f"{name}: using natural recording {wav}")
            elif engine == "piper":
                if model_path is None or not model_path.is_file():
                    raise FileNotFoundError("Piper ONNX voice model required")
                render_piper(model_path, wav, phrase)
            else:
                subprocess.run(["espeak", "-v", "fa", "-s", "135", "-p", "70",
                                "-a", "180", "-w", str(wav), phrase], check=True)
            raw = wav_to_ulaw(wav)
            lines.append(f"static constexpr std::uint8_t k{name}[] = {{")
            for i in range(0, len(raw), 22):
                lines.append("    " + ", ".join("0x%02x" % b for b in raw[i:i+22]) + ",")
            lines.append("};")
            print(f"{name}: {len(raw)} bytes of 16kHz mu-law")
    lines += ["static constexpr Clip kClips[] = {",
              *[f"    {{k{name}, sizeof(k{name})}}," for name, _ in CLIPS],
              "};", "} // namespace stackchan::app::play_audio"]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--output", type=Path, default=Path("main/play_audio_assets.hpp"))
    p.add_argument("--engine", choices=("espeak", "piper"), default="espeak")
    p.add_argument("--model", type=Path, default=None)
    p.add_argument("--recording-dir", type=Path, default=Path("assets/play_audio_fa"))
    args = p.parse_args()
    generate(args.output, engine=args.engine, model_path=args.model,
             recording_dir=args.recording_dir)
